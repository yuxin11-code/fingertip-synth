module instrument_four_voice_bank(
    input wire clk,input wire rst_n,input wire sample_enable,
    input wire [3:0] voice_gate,
    input wire [6:0] voice0_note,
    input wire [6:0] voice1_note,
    input wire [6:0] voice2_note,
    input wire [6:0] voice3_note,
    input wire [17:0] pitch_scale_q16,
    input wire [1:0] timbre_select,input wire [15:0] attack_step,
    input wire [3:0] decay_divider_limit,input wire [15:0] sustain_level,
    input wire [3:0] release_divider_limit,
    output wire signed [31:0] sample_sum
);
    wire signed [31:0] v0,v1,v2,v3;
    instrument_voice voice0(.clk(clk),.rst_n(rst_n),
    .sample_enable(sample_enable),
    .note_on(voice_gate[0]),
    .note_number(voice0_note),
    .pitch_scale_q16(pitch_scale_q16),
    .timbre_select(timbre_select),
    .attack_step(attack_step),
    .decay_divider_limit(decay_divider_limit),
    .sustain_level(sustain_level),
    .release_divider_limit(release_divider_limit),
    .sample_out(v0));
    instrument_voice voice1(.clk(clk),
    .rst_n(rst_n),
    .sample_enable(sample_enable),
    .note_on(voice_gate[1]),
    .note_number(voice1_note),
    .pitch_scale_q16(pitch_scale_q16),
    .timbre_select(timbre_select),
    .attack_step(attack_step),
    .decay_divider_limit(decay_divider_limit),
    .sustain_level(sustain_level),
    .release_divider_limit(release_divider_limit),
    .sample_out(v1));
    instrument_voice voice2(.clk(clk),.rst_n(rst_n),
    .sample_enable(sample_enable),
    .note_on(voice_gate[2]),
    .note_number(voice2_note),
    .pitch_scale_q16(pitch_scale_q16),
    .timbre_select(timbre_select),
    .attack_step(attack_step),
    .decay_divider_limit(decay_divider_limit),
    .sustain_level(sustain_level),
    .release_divider_limit(release_divider_limit),
    .sample_out(v2));
    instrument_voice voice3(.clk(clk),
    .rst_n(rst_n),
    .sample_enable(sample_enable),
    .note_on(voice_gate[3]),
    .note_number(voice3_note),
    .pitch_scale_q16(pitch_scale_q16),
    .timbre_select(timbre_select),
    .attack_step(attack_step),
    .decay_divider_limit(decay_divider_limit),
    .sustain_level(sustain_level),
    .release_divider_limit(release_divider_limit),
    .sample_out(v3));
    assign sample_sum=(v0>>>2)+(v1>>>2)+(v2>>>2)+(v3>>>2);
endmodule
